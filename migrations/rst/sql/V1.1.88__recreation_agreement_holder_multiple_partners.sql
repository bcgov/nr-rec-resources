-- Adopt FTA's agreement_holder_id so the sync has a stable key to upsert
-- against. The fta schema only exists where the FTA migrations have been run.
do $$
begin
    if to_regclass('fta.recreation_agreement_holder') is not null then
        execute $sql$
            update rst.recreation_agreement_holder r
            set agreement_holder_id = f.agreement_holder_id
            from fta.recreation_agreement_holder f
            where f.forest_file_id = r.rec_resource_id
              and f.client_number is not distinct from r.client_number
              and f.revision_count is not distinct from r.revision_count
              and r.agreement_holder_id is null
        $sql$;
    end if;
end
$$;

with unmatched as (
    select rec_resource_id,
           1000000 + row_number() over (order by rec_resource_id) as new_id
    from rst.recreation_agreement_holder
    where agreement_holder_id is null
)
update rst.recreation_agreement_holder r
set agreement_holder_id = u.new_id
from unmatched u
where u.rec_resource_id = r.rec_resource_id
  and r.agreement_holder_id is null;

