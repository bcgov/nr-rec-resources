-- Explicitly-inserted ids do not advance an identity sequence, so the sequence
-- must be pushed past the range FTA's own ids occupy.
select setval(
    pg_get_serial_sequence('rst.recreation_agreement_holder', 'agreement_holder_id'),
    greatest(
        1000000,
        coalesce((select max(agreement_holder_id) from rst.recreation_agreement_holder), 0)
    ),
    true
);

